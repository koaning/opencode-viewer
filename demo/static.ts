/** The dashboard's dark palette, lifted from its own `[data-mode="dark"]` rule so the two can't drift apart. */
const darkPalette = (css: string) => {
  const match = css.match(/\.ocv-root\[data-mode="dark"\]\s*\{([^}]*)\}/)
  if (!match) throw new Error("style.css has no .ocv-root[data-mode=\"dark\"] rule to reuse")
  return match[1]!
}

const darkRules = (scope: string, palette: string) => `
${scope} {${HOST_DARK}
}
${scope} .ocv-root {${palette}}`

const radios = (name: string, options: readonly (readonly [string, string])[], checked: string) =>
  options
    .map(
      ([id, label]) =>
        `<input type="radio" name="${name}" id="${id}"${id === checked ? " checked" : ""}><label for="${id}">${label}</label>`,
    )
    .join("")

/** Safe inside a <script> element: nothing in it can close the element or open a comment. */
const inlineScript = (code: string) => code.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--")

export const staticPage = (input: { readonly dashboard: string; readonly css: string; readonly script: string }) => {
  const palette = darkPalette(input.css)
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>opencode-viewer · a session dashboard for OpenCode Desktop</title>
    <meta name="description" content="A live dashboard of the current OpenCode session, in OpenCode Desktop's side region: context, tokens, cost, turns and tools." />
    <!-- Generated by \`bun run screenshot\` (demo/shoot.ts, demo/static.ts). Don't edit by hand. -->
    <style>${PAGE_CSS}</style>
    <style>${input.css}</style>
    <style>${darkRules("body:has(#t-dark:checked)", palette)}
@media (prefers-color-scheme: dark) {${darkRules("body:not(:has(#t-light:checked))", palette)}
}
    </style>
  </head>
  <body>
    <main class="page">
      <h1>opencode-viewer</h1>
      <p>
        A live dashboard of the current <a href="https://opencode.ai">OpenCode</a> session, in a tab of OpenCode
        Desktop's side region: what fills the context, tokens and cost, every request, a trace of each turn, and your
        tools. Below is the plugin's real UI on a made-up session: hover anything, click a request column or a turn, or
        replay the session. <a href="${REPO}">Install it from GitHub →</a>
      </p>
      <div class="controls">
        <span><span class="name">Theme</span><span class="seg">${radios("theme", [["t-auto", "Auto"], ["t-light", "Light"], ["t-dark", "Dark"]], "t-auto")}</span></span>
        <span><span class="name">Panel width</span><span class="seg">${radios("width", [["w-380", "380px"], ["w-560", "560px"], ["w-720", "720px"]], "w-560")}</span></span>
      </div>
      <div class="frame"><div id="app">${input.dashboard}</div></div>
      <noscript><p class="foot">A snapshot: turn on JavaScript for tooltips, clicks and the replay.</p></noscript>
    </main>
    <script type="module">${inlineScript(input.script)}</script>
  </body>
</html>
`
}
