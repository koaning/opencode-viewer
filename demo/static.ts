// The docs page, one self-contained file: the dashboard as rendered once in a browser (see shoot.ts), and the live one
// bundled inline, which takes over on load (docs.tsx). It needs no server, no OpenCode and no build, so GitHub Pages
// serves docs/ as it is, and it opens from disk too. Without JavaScript the snapshot stays. Theme and panel width are
// radio buttons and `:has()`, so they work either way; the panel width drives the dashboard's container queries.

const REPO = "https://github.com/koaning/opencode-viewer"

/** What Desktop sets per theme; the dashboard's CSS carries light fallbacks for most of them. */
